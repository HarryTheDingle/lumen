    private fun stripTrailingRegion(name: String): String {
        val normalized = normalizeNameKey(name)
        for (region in REGION_SUFFIXES) {
            if (normalized.endsWith(" $region") && normalized.length > region.length + 2) {
                return normalized.substring(0, normalized.length - region.length).trim()
            }
        }
        return normalized
    }
