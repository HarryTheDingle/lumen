    private val byId: Map<String, UkChannelEntry> = entries.associateBy { it.id }

    private val byNameKey: Map<String, List<UkChannelEntry>> = buildMap<String, MutableList<UkChannelEntry>> {
        for (entry in this@UkChannelRegistry.entries) {
            val allNames = listOf(entry.name) + entry.aliases
            for (candidate in allNames) {
                val key = normalizeNameKey(candidate)
                if (key.isNotEmpty()) {
                    getOrPut(key) { mutableListOf() }.add(entry)
                }
            }
        }
    }

    private val byEpgId: Map<String, UkChannelEntry> = buildMap {
        for (entry in this@UkChannelRegistry.entries) {
            put(entry.id.lowercase(), entry)
            for (epg in entry.epgIds) {
                put(epg.lowercase(), entry)
            }
        }
    }

    internal fun normalizeNameKey(name: String): String {
        val folded = buildString(name.length) {
            for (ch in name.lowercase()) {
                append(ACCENT_MAP[ch] ?: ch)
            }
        }
        val plusHandled = folded
            .replace(PLUS_ONE_KEY_REGEX, " plus1")
            .replace(TRAILING_PLUS_KEY_REGEX, "plus")
            .replace("&", " ")
        return buildString(plusHandled.length) {
            var prevSpace = true
            for (ch in plusHandled) {
                if (ch.isLetterOrDigit()) {
                    append(ch)
                    prevSpace = false
                } else if (!prevSpace) {
                    append(' ')
                    prevSpace = true
                }
            }
        }.trim()
    }

    private fun hasPlusOneMarker(text: String): Boolean =
        PLUS_ONE_MARKER_REGEX.containsMatchIn(text) ||
            text.lowercase().contains("plus1")

    private fun isUsHint(tvgId: String?, rawGroup: String?): Boolean {
        val t = tvgId?.lowercase().orEmpty()
        val g = rawGroup?.lowercase().orEmpty()
        return t.endsWith(".us") ||
            US_GROUP_HINT_REGEX.containsMatchIn(g)
    }

    private fun pickCandidate(
        candidates: List<UkChannelEntry>?,
        tvgId: String?,
        rawGroup: String?,
    ): UkChannelEntry? {
        if (candidates.isNullOrEmpty()) return null
        if (candidates.size == 1) return candidates[0]
        val usHint = isUsHint(tvgId, rawGroup)
        return if (usHint) {
            candidates.firstOrNull { it.category == ChannelCategory.US_ENGLISH } ?: candidates[0]
        } else {
            candidates.firstOrNull { it.category != ChannelCategory.US_ENGLISH } ?: candidates[0]
        }
    }

    /** Looks up a canonical entry by normalized channel name, optional XMLTV [tvgId], and [rawGroup]. */
    fun match(cleanedName: String, tvgId: String? = null, rawGroup: String? = null): UkChannelEntry? {
        val trimmedName = cleanedName.trim()
        val namePlusOne = hasPlusOneMarker(trimmedName)

        if (trimmedName.isNotEmpty()) {
            val key = normalizeNameKey(trimmedName)
            pickCandidate(byNameKey[key], tvgId, rawGroup)?.let { return it }

            val regionKey = stripTrailingRegion(key)
            if (regionKey != key) {
                pickCandidate(byNameKey[regionKey], tvgId, rawGroup)?.let { return it }
            }
        }

        val normalizedTvg = tvgId?.trim()?.lowercase()?.takeIf { it.isNotEmpty() }
        if (normalizedTvg != null) {
            val epgMatch = byEpgId[normalizedTvg] ?: run {
                val stem = normalizedTvg.substringBefore('.')
                val ukCandidate = byEpgId["$stem.uk"] ?: byEpgId["$stem.ie"] ?: byEpgId["$stem.us"]
                ukCandidate
            }
            if (epgMatch != null && hasPlusOneMarker(epgMatch.name) == namePlusOne) {
                return epgMatch
            }
        }
        return null
    }

